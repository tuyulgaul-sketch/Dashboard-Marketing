const L = (...lines) => lines.join("\n");
const replaceOnce = (source, label, before, after) => {
  const count = source.split(before).length - 1;
  if (count !== 1) throw new Error(`${label}: expected 1 match, found ${count}`);
  return source.replace(before, after);
};
const insertBeforeOnce = (source, label, anchor, insertion) => {
  const count = source.split(anchor).length - 1;
  if (count !== 1) throw new Error(`${label}: expected 1 anchor, found ${count}`);
  return source.replace(anchor, insertion + anchor);
};

