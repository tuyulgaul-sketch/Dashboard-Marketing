create or replace function public.log_activity_update_event_v2()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Ignore an update that only touches updated_at.
  if (
    (to_jsonb(new) - 'updated_at')
    is distinct from
    (to_jsonb(old) - 'updated_at')
  ) then
    insert into public.activity_events (
      activity_id,
      event_type,
      actor_profile_id,
      source_id
    )
    values (
      new.id,
      'ACTIVITY_UPDATED',
      public.activity_event_actor_profile_id_v2(),
      new.id
    );
  end if;

  return new;
end;
$$;

drop trigger if exists trg_activity_update_event_v2
  on public.activities;

create trigger trg_activity_update_event_v2
after update on public.activities
for each row
execute function public.log_activity_update_event_v2();

create or replace function public.log_activity_related_event_v2()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_activity_id uuid;
  v_source_id uuid;
begin
  if tg_op = 'DELETE' then
    v_activity_id := old.activity_id;
    v_source_id := old.id;
  else
    v_activity_id := new.activity_id;
    v_source_id := new.id;
  end if;

  insert into public.activity_events (
    activity_id,
    event_type,
    actor_profile_id,
    source_id
  )
  values (
    v_activity_id,
    upper(tg_table_name || '_' || tg_op),
    public.activity_event_actor_profile_id_v2(),
    v_source_id
  );

  return coalesce(new, old);
end;
$$;

