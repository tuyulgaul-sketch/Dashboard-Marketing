-- Server-side canonical unseen state.
create or replace function public.get_my_activity_attention_v2()
returns table (
  activity_id uuid,
  unseen_count integer,
  latest_event_at timestamptz,
  last_seen_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select public.current_profile_id() as id
  )
  select
    e.activity_id,
    count(*)::integer as unseen_count,
    max(e.created_at) as latest_event_at,
    max(avs.last_seen_at) as last_seen_at
  from public.activity_events e
  cross join me
  left join public.activity_view_states avs
    on avs.activity_id = e.activity_id
   and avs.profile_id = me.id
  where
    me.id is not null
    and public.can_view_activity_id(e.activity_id)
    and e.actor_profile_id is distinct from me.id
    and e.created_at > coalesce(
      avs.last_seen_at,
      '1970-01-01 00:00:00+00'::timestamptz
    )
  group by e.activity_id;
$$;

revoke all
  on function public.get_my_activity_attention_v2()
  from public;

grant execute
  on function public.get_my_activity_attention_v2()
  to authenticated;

