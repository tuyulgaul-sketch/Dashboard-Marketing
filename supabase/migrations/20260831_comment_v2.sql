create or replace function public.log_activity_comment_event_v2()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.activity_events (
    activity_id,
    event_type,
    actor_profile_id,
    source_id
  )
  values (
    new.activity_id,
    case
      when new.parent_comment_id is null then 'COMMENT_ADDED'
      else 'COMMENT_REPLIED'
    end,
    public.activity_event_actor_profile_id_v2(),
    new.id
  );

  return new;
end;
$$;

