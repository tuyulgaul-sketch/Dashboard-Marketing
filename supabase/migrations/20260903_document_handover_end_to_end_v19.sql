-- Avoid duplicate Push notifications from legacy compatibility notification
-- rows. Modern public.notifications is the sole Bell/Push source for Tanda
-- Terima after V19.
create or replace function public.enqueue_legacy_push_v13()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_recipient_legacy_id text;
  v_recipient_profile_id uuid;
  v_outbox_id bigint;
begin
  if new.storage_key <> 'pertalife_notifications' then
    return new;
  end if;

  if trim(coalesce(new.payload ->> 'linkPath', '')) = '/tanda-terima' then
    return new;
  end if;

  v_recipient_legacy_id := trim(coalesce(new.payload->>'recipientUserId', ''));

  if v_recipient_legacy_id = '' then
    return new;
  end if;

  select p.id
  into v_recipient_profile_id
  from public.profiles p
  where p.active = true
    and p.legacy_user_id = v_recipient_legacy_id
  limit 1;

  if v_recipient_profile_id is null then
    return new;
  end if;

  insert into public.push_outbox_v13 (
    source,
    source_id,
    recipient_profile_id,
    notification_type,
    module,
    title,
    message,
    link_path
  )
  values (
    'LEGACY_NOTIFICATION',
    new.entity_id,
    v_recipient_profile_id,
    'LEGACY_BELL',
    'LEGACY',
    coalesce(nullif(trim(new.payload->>'title'), ''), 'Dashboard Marketing'),
    coalesce(nullif(trim(new.payload->>'message'), ''), 'Ada notifikasi baru.'),
    nullif(trim(coalesce(new.payload->>'linkPath', '')), '')
  )
  on conflict (source, source_id, recipient_profile_id)
  do nothing
  returning id into v_outbox_id;

  if v_outbox_id is not null then
    perform public.kick_push_dispatch_v13(v_outbox_id);
  end if;

  return new;
end;
$$;

commit;
